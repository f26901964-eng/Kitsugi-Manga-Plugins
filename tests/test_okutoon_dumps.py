"""Check the OkuToon selectors against the HTML the user saved from the site.

The dumps in docs/html-dumps/okutoon are the pages themselves, so this test fails as soon
as a selector in the extension stops matching the markup the site really serves.
"""
import re
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DUMPS = ROOT / "docs/html-dumps/okutoon"
SOURCE = ROOT / "keiyoushi-extensions-tr/src/tr/okutoon/src/eu/kanade/tachiyomi/extension/okutoon"


def dump(name):
    path = DUMPS / name
    if not path.is_file():
        raise unittest.SkipTest(f"dump yok: {name}")
    return path.read_text(encoding="utf-8", errors="replace")


def source(name):
    return (SOURCE / name).read_text(encoding="utf-8")


class OkutoonDumpTests(unittest.TestCase):
    def test_catalogue_page_uses_the_listed_card_markup(self):
        page = dump("message-71.txt")  # /tur?q=chainsaw+man
        self.assertIn('class="series-grid"', page)
        cards = re.findall(r'<a href="(/[a-z0-9-]+)" class="series-card">', page)
        self.assertTrue(cards, "series-card bağlantıları okunamadı")
        self.assertIn('class="series-card-title"', page)
        self.assertIn('class="series-card-cover"', page)
        # The extension reads the href straight off the card, so it must be the <a>.
        self.assertIn('.series-grid .series-card', source("OkuToon.kt"))

    def test_catalogue_paging_uses_the_next_link(self):
        page = dump("message-71.txt")
        self.assertNotIn('a.pagination-btn', page)  # single result, no pager
        home = dump("message-70.txt")
        self.assertIn('class="pagination', home)
        self.assertIn('[rel=next]', source("OkuToon.kt"))

    def test_search_form_parameters_are_the_ones_the_extension_sends(self):
        page = dump("message-71.txt")
        for field in ('name="q"', 'name="sira"', 'name="durum"', 'name="tip"', 'name="k[]"', 'name="sayfa"'):
            if field == 'name="sayfa"':
                continue  # paging is generated by the site, not part of the search form
            self.assertIn(field, page)
        # Every sort value the filter offers must exist in the site's own dropdown.
        sorts = re.findall(r'<option value="([a-z]+)"', page)
        for value in ("newest", "updated", "popular", "rating", "az"):
            self.assertIn(value, sorts)
        # The genres offered must be the site's own checkbox values.
        site_genres = set(re.findall(r'name="k\[\]" value="([a-z-]+)"', page))
        self.assertTrue(site_genres)
        filters = source("Filters.kt")
        extension_genres = set(re.findall(r'Genre\("[^"]+", "([a-z-]+)"\)', filters))
        self.assertEqual(site_genres - extension_genres, set(), "sitede olup eklentide olmayan tür")

    def test_series_page_detail_and_chapter_selectors(self):
        page = dump("message-72.txt")  # /chainsaw-man
        for selector in (
            'class="series-detail-title"',
            'class="series-detail-author"',
            'class="series-detail-cover"',
            'class="series-detail-genres"',
            'class="series-status series-status--ongoing"',
            'data-series-description-content',
        ):
            self.assertIn(selector, page, selector)

        # Chapter rows: the wrapper carries .chapter-item, the link sits inside it.
        rows = page.count('<div class="chapter-item"')
        self.assertGreater(rows, 200)
        self.assertIn('class="chapter-item-link"', page)
        self.assertIn('class="chapter-title"', page)
        self.assertIn('class="chapter-date"', page)
        # Dates are Turkish long form, which is what the extension parses.
        self.assertRegex(page, r'class="chapter-date">\d{1,2} (Ocak|Şubat|Mart|Nisan|Mayıs|Haziran|Temmuz|Ağustos|Eylül|Ekim|Kasım|Aralık) \d{4}<')

    def test_reader_page_exposes_every_page_image(self):
        page = dump("message-73.txt")  # /chainsaw-man/bolum-1
        self.assertIn('id="readerPages"', page)
        images = re.findall(r'<img[^>]*class="reader-page"[^>]*>', page)
        self.assertEqual(len(images), 53, "okuyucudaki sayfa sayısı değişti")
        srcs = [re.search(r'src="([^"]+)"', image) for image in images]
        self.assertTrue(all(srcs), "her sayfa görselinde src var")
        hosts = {re.match(r'https://([^/]+)/', match.group(1)).group(1) for match in srcs}
        self.assertEqual(hosts, {"om-cdn.okutoon.com"})
        # The extension must read the CDN host, not the site host.
        self.assertIn('om-cdn', page)
        self.assertIn('img.reader-page', source("OkuToon.kt"))

    def test_reader_lists_chapters_for_the_dropdown(self):
        page = dump("message-73.txt")
        self.assertIn('class="reader-chapter-list-item', page)
        self.assertIn('class="reader-chapter-list-title"', page)


if __name__ == "__main__":
    unittest.main()
